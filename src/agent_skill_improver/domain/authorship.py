"""Authorship class: who actually produced a conversation.

This module exists because of one measured property of real corpora: an
orchestrated agent loop talks to itself far more often than a human talks to an
agent. In the environment this tool was designed against, threads generated by an
orchestrator outnumbered human working sessions by roughly 25 to 1 over a 30-day
window.

That ratio is the whole problem. A judge pointed at "all conversations" grades
machine traffic almost all of the time, and an improver fed those scores proposes
skill edits optimised for how the loop talks to itself. It is a closed circuit
with a human name on it. Meanwhile the scarce class is the valuable one: the
human sessions are where a skill was actually loaded and actually mis-served a
person.

So authorship class is a first-class selection dimension, not a statistic. Three
honest properties:

* Classification is **heuristic**, and it says so. It reads titles, agent
  metadata and message origin markers; it cannot read intent.
* An unrecognised conversation is :data:`CLASS_UNKNOWN`, never silently folded
  into ``human``. Unknown gets its own selection bucket, because a record nobody
  can classify is exactly the one a human should look at.
* Markers are configurable. Hard-coding one orchestrator's title would make this
  useless on any other setup.
"""

from __future__ import annotations

import re
from typing import Any, Iterable, Sequence

from .redaction import quoted_value

CLASS_HUMAN = "human"
CLASS_ORCHESTRATED = "orchestrated"
CLASS_UNKNOWN = "unknown"

#: Post-fetch classes. Available only once a conversation has been exported.
CLASSES = (CLASS_HUMAN, CLASS_ORCHESTRATED, CLASS_UNKNOWN)

#: Pre-fetch label for a thread whose title matched no orchestrator marker.
#:
#: Deliberately NOT ``human``. A title cannot prove a human wrote a thread, and
#: labelling it ``human`` would overstate what discovery knows -- while labelling
#: it ``unknown`` reads as "we failed to classify it" when in fact a specific,
#: useful thing is known: it is not agent-titled. Discovery is therefore an honest
#: two-way split, and the three-way class is decided later, from the transcript.
CLASS_NOT_AGENT_TITLED = "not-agent-titled"

#: The label space selection actually buckets on.
DISCOVERY_CLASSES = (CLASS_NOT_AGENT_TITLED, CLASS_ORCHESTRATED)

#: Default title markers for orchestrator-generated threads. Configurable via
#: ``[selection].agent_title_markers`` precisely because this default is a guess
#: about one environment.
DEFAULT_AGENT_TITLE_MARKERS: tuple[str, ...] = (
    "orchestrator run",
    "autonomous iteration",
    "dispatcher",
)

#: Substrings that mark a first turn as a generated role prompt rather than a
#: human request. Matched case-insensitively against the opening user message.
DEFAULT_ROLE_PROMPT_MARKERS: tuple[str, ...] = (
    "you are the engineer",
    "you are the reviewer",
    "you are the tester",
    "role prompt",
    "iteration id",
)

_WS = re.compile(r"\s+")


def _norm(text: str) -> str:
    return _WS.sub(" ", (text or "").strip().lower())


def _phrase_present(haystack: str, needle: str) -> bool:
    """Whole-phrase, word-boundary match.

    Word boundaries are not decoration here: a bare substring test for a short
    marker matches unrelated words and produces a confident wrong classification,
    which is worse than ``unknown``.
    """
    if not needle:
        return False
    pattern = re.compile(rf"(?<![a-z0-9]){re.escape(needle)}(?![a-z0-9])")
    return bool(pattern.search(haystack))


def classify_title(
    title: str, *, agent_title_markers: Sequence[str] = DEFAULT_AGENT_TITLE_MARKERS
) -> str:
    """Classify from the title alone -- the only signal available pre-fetch.

    Returns one of :data:`DISCOVERY_CLASSES`. Selection has to bound the batch
    *before* paying to export anything, so the fairness dimension must be
    computable from discovery metadata alone.
    """
    norm = _norm(title)
    for marker in agent_title_markers:
        if _phrase_present(norm, _norm(marker)):
            return CLASS_ORCHESTRATED
    return CLASS_NOT_AGENT_TITLED


def classify_thread(
    thread: Any,
    *,
    agent_title_markers: Sequence[str] = DEFAULT_AGENT_TITLE_MARKERS,
) -> str:
    """Classify a discovery record (duck-typed: needs ``title``)."""
    return classify_title(
        getattr(thread, "title", "") or "", agent_title_markers=agent_title_markers
    )


def classify_conversation(
    conversation: Any,
    *,
    agent_title_markers: Sequence[str] = DEFAULT_AGENT_TITLE_MARKERS,
    role_prompt_markers: Sequence[str] = DEFAULT_ROLE_PROMPT_MARKERS,
) -> tuple[str, tuple[str, ...]]:
    """Classify a fetched conversation, returning ``(class, reasons)``.

    Post-fetch there are more signals than the title, so this can promote a
    thread from ``unknown`` to a decided class -- and it records *why*, because a
    classification with no stated reason is not reviewable.

    A reason quotes what the export says, through ``quoted_value``: the title,
    agent name and origin are untrusted text that lands in the receipt and the
    run's JSON output. Measured before: each was quoted whole with ``repr``, so a
    200,000-character title made a 210 KB receipt where the run otherwise
    writes 10 KB, and a credential in a title was copied there unmasked (one in
    an agent name lowercased, otherwise whole). The agent name and origin are
    quoted as written, not as lowercased for matching, which would hide a key
    from the masking shapes.
    """
    reasons: list[str] = []
    title = getattr(conversation, "title", "") or ""
    by_title = classify_title(title, agent_title_markers=agent_title_markers)
    if by_title == CLASS_ORCHESTRATED:
        reasons.append(f"title matches an orchestrator marker: {quoted_value(title)}")

    raw_agent_name = getattr(conversation, "agent_name", "") or ""
    agent_name = _norm(raw_agent_name)
    if agent_name:
        reasons.append(f"thread carries an agent_name ({quoted_value(raw_agent_name)})")

    opening_generated = False
    users = getattr(conversation, "user_messages", ()) or ()
    if users:
        first = users[0]
        body = _norm(getattr(first, "text", "") or "")
        for marker in role_prompt_markers:
            if _phrase_present(body, _norm(marker)):
                opening_generated = True
                reasons.append(f"opening user turn reads as a generated role prompt ({marker!r})")
                break
        raw_origin = getattr(first, "origin", "") or ""
        origin = _norm(raw_origin)
        if origin and origin not in ("user", "human", "interactive"):
            opening_generated = True
            reasons.append(
                f"opening user turn has a non-human origin marker ({quoted_value(raw_origin)})"
            )

    if by_title == CLASS_ORCHESTRATED or opening_generated or agent_name:
        return CLASS_ORCHESTRATED, tuple(reasons)
    if users:
        reasons.append("a human user turn opens the thread and no orchestrator marker matched")
        return CLASS_HUMAN, tuple(reasons)
    reasons.append("no user turn and no orchestrator marker; class cannot be decided")
    return CLASS_UNKNOWN, tuple(reasons)


def class_histogram(values: Iterable[str], *, declared: Sequence[str] = CLASSES) -> dict[str, int]:
    """Counts for every declared class, including zeros.

    Zeros are included on purpose: "human: 0" is a finding, whereas an absent key
    is indistinguishable from a key nobody thought to count. Labels outside
    ``declared`` are counted under their own name rather than being folded into a
    catch-all, because silently re-bucketing a label loses the very distinction
    the caller asked for.
    """
    out = {name: 0 for name in declared}
    for value in values:
        key = value or CLASS_UNKNOWN
        out[key] = out.get(key, 0) + 1
    return out
